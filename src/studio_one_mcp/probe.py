"""Throwaway probe for the script-side command bridge (issue #3).

Surface-XML ``<Command>`` mappings don't fire macros. This checks whether calling
``Host.GUI.Commands.interpretCommand("Macros", "Macro <base64>")`` from a device
script does, on this machine's Studio One, before we build anything on it.

The ``StudioOneMCP Probe`` device (``studio-one-devices/MCPProbe``) answers
requests through a mailbox folder: we write ``request.json``, press a doorbell
note on a MIDI port the device receives from, and read ``response.json``.
Pattern from NeanderthalMan/studio-one-mcp (MIT).

    python -m studio_one_mcp.probe install
    python -m studio_one_mcp.probe ping
    python -m studio_one_mcp.probe macros
    python -m studio_one_mcp.probe run-macro "My Macro"
"""

from __future__ import annotations

import contextlib
import json
import os
import platform
import shutil
import time
import uuid
from collections.abc import Callable, Iterator
from pathlib import Path
from typing import Any

import click

from studio_one_mcp.macro_writer import macro_command_name

DEVICE_NAME = "MCPProbe"
DOORBELL_NOTE = 119  # must match address="#77" in MCPProbe.surface.xml
DEFAULT_PORT = "StudioOneMCP"
_DEVICE_SRC = Path(__file__).resolve().parents[2] / "studio-one-devices" / DEVICE_NAME
_IS_MAC = platform.system() == "Darwin"


class ProbeError(RuntimeError):
    pass


def mailbox_dir() -> Path:
    if env := os.environ.get("STUDIO_ONE_MCP_PROBE_DIR"):
        return Path(env)
    if _IS_MAC:
        return Path.home() / "Library" / "Application Support" / "StudioOneMCP" / "probe"
    return Path.home() / ".studio-one-mcp" / "probe"


def file_url(path: Path) -> str:
    """Studio One's own files store file URLs unencoded ("file:///…/Studio One/…")."""
    p = path.resolve().as_posix()
    return "file://" + ("" if p.startswith("/") else "/") + p


def profile_dirs() -> list[Path]:
    """Studio One user profiles ("Studio One 7", "Studio Pro 8", …), newest first."""
    if _IS_MAC:
        roots = [
            Path.home() / "Library" / "Application Support" / v for v in ("PreSonus", "Fender")
        ]
    else:
        appdata = Path(os.environ.get("APPDATA", Path.home() / "AppData" / "Roaming"))
        roots = [appdata / v for v in ("PreSonus", "Fender")]
    found = [
        d
        for r in roots
        if r.is_dir()
        for d in r.iterdir()
        if d.is_dir() and d.name.startswith(("Studio One", "Studio Pro"))
    ]
    return sorted(found, key=lambda d: d.stat().st_mtime, reverse=True)


def install(profile: Path, mailbox: Path) -> Path:
    """Copy the probe device into *profile*'s User Devices and point it at *mailbox*."""
    target = profile / "User Devices" / DEVICE_NAME
    if target.exists():
        shutil.rmtree(target)
    shutil.copytree(_DEVICE_SRC, target)
    mailbox.mkdir(parents=True, exist_ok=True)
    config = {"mailbox": file_url(mailbox) + "/"}
    (target / "ProbeConfig.js").write_text(
        "// Generated by python -m studio_one_mcp.probe install\n"
        f"var ProbeConfig = {json.dumps(config, indent=2)};\n",
        encoding="utf-8",
    )
    return target


class Probe:
    """Sends one request at a time through the mailbox; *ring* presses the doorbell."""

    def __init__(self, mailbox: Path, ring: Callable[[], None]) -> None:
        self.mailbox = mailbox
        self.ring = ring

    def _read(self, name: str) -> Any:
        try:
            return json.loads((self.mailbox / name).read_text(encoding="utf-8-sig"))
        except (OSError, ValueError):
            return None

    def status(self) -> Any:
        return self._read("status.json")

    def call(self, op: str, args: dict[str, Any] | None = None, timeout: float = 5.0) -> Any:
        req_id = uuid.uuid4().hex
        self.mailbox.mkdir(parents=True, exist_ok=True)
        tmp = self.mailbox / "request.json.tmp"
        tmp.write_text(
            json.dumps({"id": req_id, "op": op, "args": args or {}}) + "\n", encoding="utf-8"
        )
        os.replace(tmp, self.mailbox / "request.json")

        deadline = time.monotonic() + timeout
        next_ring = 0.0
        while time.monotonic() < deadline:
            now = time.monotonic()
            if now >= next_ring:  # re-press until answered; the device skips ids it has answered
                self.ring()
                next_ring = now + 0.15
            reply = self._read("response.json")
            if isinstance(reply, dict) and reply.get("id") == req_id:
                if not reply.get("ok"):
                    raise ProbeError(reply.get("error", "unknown error"))
                return reply.get("result")
            time.sleep(0.02)
        raise ProbeError(self._timeout_hint())

    def _timeout_hint(self) -> str:
        status = self.status()
        if status is None:
            return (
                "no answer, and no status.json: the probe device isn't loaded. Install it, "
                "restart Studio One, and add External Devices ▸ StudioOneMCP ▸ StudioOneMCP Probe."
            )
        if not status.get("ticks"):
            return (
                "no answer: the probe is loaded but has never heard the doorbell. Check its "
                "Receive From port, or try --channel 1."
            )
        return "no answer, though the doorbell arrives: see Studio One's console for script errors."


@contextlib.contextmanager
def doorbell(port: str, channel: int) -> Iterator[Callable[[], None]]:
    """Open *port* (an existing output whose name contains it, else a virtual port) and yield a ring()."""
    import rtmidi

    out = rtmidi.MidiOut()
    names = out.get_ports()
    match = next((i for i, n in enumerate(names) if port.lower() in n.lower()), None)
    if match is not None:
        out.open_port(match)
    else:
        out.open_virtual_port(port)
        if port == DEFAULT_PORT:
            from studio_one_mcp import coremidi

            with contextlib.suppress(Exception):
                coremidi.pin_unique_id(port)
        time.sleep(0.5)  # let Studio One see the new port before the first press
    status = 0x90 | ((channel - 1) & 0x0F)

    def ring() -> None:
        out.send_message([status, DOORBELL_NOTE, 127])
        out.send_message([status, DOORBELL_NOTE, 0])

    try:
        yield ring
    finally:
        out.close_port()


# ---- CLI ----------------------------------------------------------------------


def _echo(value: Any) -> None:
    click.echo(json.dumps(value, indent=2))


@click.group()
@click.option(
    "--port",
    default=DEFAULT_PORT,
    show_default=True,
    help="MIDI port the probe device receives from (an existing output, e.g. an IAC bus, "
    "or a virtual port opened by this command).",
)
@click.option(
    "--channel",
    type=click.IntRange(1, 16),
    default=16,
    show_default=True,
    help="Doorbell channel: 16, or 1 for the alternative surface form.",
)
@click.option("--timeout", type=float, default=5.0, show_default=True)
@click.pass_context
def cli(ctx: click.Context, port: str, channel: int, timeout: float) -> None:
    """Probe whether Studio One runs commands and macros called from a device script."""
    ctx.obj = {"port": port, "channel": channel, "timeout": timeout}


def _call(ctx: click.Context, op: str, args: dict[str, Any] | None = None) -> Any:
    o = ctx.obj
    with doorbell(o["port"], o["channel"]) as ring:
        try:
            return Probe(mailbox_dir(), ring).call(op, args, o["timeout"])
        except ProbeError as e:
            raise click.ClickException(str(e)) from e


@cli.command("install")
@click.option(
    "--profile",
    type=click.Path(file_okay=False, path_type=Path),
    help="Studio One user profile folder (default: the newest one found).",
)
def install_cmd(profile: Path | None) -> None:
    """Copy the probe device into Studio One's User Devices."""
    if profile is None:
        found = profile_dirs()
        if not found:
            raise click.ClickException("no Studio One profile found; pass --profile")
        profile = found[0]
    target = install(profile, mailbox_dir())
    click.echo(f"Installed → {target}\nMailbox  → {mailbox_dir()}")
    click.echo(
        "Next: restart Studio One, then Preferences ▸ External Devices ▸ Add… ▸ StudioOneMCP ▸ "
        f"StudioOneMCP Probe. Receive From = {DEFAULT_PORT} (run `hold` first so the port exists), "
        "Send To = None."
    )


@cli.command()
@click.pass_context
def hold(ctx: click.Context) -> None:
    """Keep the MIDI port open (so Studio One can see it) until Ctrl+C."""
    with doorbell(ctx.obj["port"], ctx.obj["channel"]):
        click.echo(f"Port {ctx.obj['port']!r} is open. Ctrl+C to close.")
        with contextlib.suppress(KeyboardInterrupt):
            while True:
                time.sleep(1)


@cli.command()
@click.pass_context
def ping(ctx: click.Context) -> None:
    """Check the probe answers, and which Host.GUI.Commands members exist."""
    _echo(_call(ctx, "ping"))


@cli.command("commands")
@click.option("--filter", "flt", default="", help="Substring of 'Category Name'.")
@click.pass_context
def commands_cmd(ctx: click.Context, flt: str) -> None:
    """List Studio One's commands, live."""
    r = _call(ctx, "listCommands", {"filter": flt})
    for c in r["commands"]:
        click.echo(f"{c['category']}/{c['name']}")
    click.echo(f"({len(r['commands'])} shown of {r['seen']})")


@cli.command()
@click.option("--filter", "flt", default="")
@click.pass_context
def macros(ctx: click.Context, flt: str) -> None:
    """List macros by title (decoded from 'Macro <base64>')."""
    import base64

    r = _call(ctx, "listCommands", {"filter": "Macros "})
    for c in r["commands"]:
        if c["category"] != "Macros":
            continue
        name = c["name"]
        title = name
        if name.startswith("Macro "):
            with contextlib.suppress(ValueError):
                title = base64.b64decode(name[6:]).decode("utf-8")
        if flt.lower() in title.lower():
            click.echo(title)


@cli.command()
@click.argument("category")
@click.argument("name")
@click.option("--check", is_flag=True, help="Only ask whether it's enabled.")
@click.pass_context
def run(ctx: click.Context, category: str, name: str, check: bool) -> None:
    """Run a built-in command, e.g. run Edit Undo."""
    _echo(_call(ctx, "command", {"category": category, "name": name, "checkOnly": check}))


@cli.command("run-macro")
@click.argument("title")
@click.option("--check", is_flag=True, help="Only ask whether it's enabled.")
@click.pass_context
def run_macro(ctx: click.Context, title: str, check: bool) -> None:
    """Run a macro by its exact title."""
    name = macro_command_name(title)
    _echo(
        {
            "command": f"Macros/{name}",
            **_call(ctx, "command", {"category": "Macros", "name": name, "checkOnly": check}),
        }
    )


if __name__ == "__main__":
    cli()
